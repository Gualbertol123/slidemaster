/* Third-party notices (LI-01, AUDIT-2 LIC-1, ADR-020): THIRD-PARTY-NOTICES.txt at the repository root (shipped in every
   release: tools/make_release.py ROOT_FILES and REQUIRED) and its zlib + base64 copy the page shows in ⚙ Options › About ›
   Licences (app/src/ui/notices-data.ts, inflated only when that opens).
   The entries come from what the page and the core worker REALLY bundle: both are bundled here as app/vite.config.ts
   bundles them, and every package esbuild's metafile shows bytes from gets its licence file from node_modules; every
   inlined WASM folder (core/src/…/wasm/) needs an entry in VENDORED below and all its LICENSE-* / COPYING-* files.
   A package without a licence file, or a WASM folder or licence file nobody listed, stops the script.
   app/tests/notices.test.ts and helper/tests/test_release.py fail when the committed files are out of date.
       node tools/notices.mjs            write both files
       node tools/notices.mjs --check    exit 1 when either is out of date */
import fs from "node:fs";
import path from "node:path";
import { deflateSync, inflateSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const NOTICES_FILE = "THIRD-PARTY-NOTICES.txt", PAGE_FILE = "app/src/ui/notices-data.ts", APACHE = "tools/licenses/Apache-2.0.txt";
export const isLicence = (/** @type {string} */ f) => /^(LICEN[CS]E|COPYING)([-.].*)?$/i.test(f);

/* the inlined WASM engines: folder → what is in it (the version is checked against the vendored file's header) */
const VENDORED = {
  "core/src/calc/wasm": [
    { name: "IronCalc", version: "0.9.0", check: ["ironcalc-wasm.ts", "@ironcalc/wasm@0.9.0"], licence: "MIT (chosen; or Apache-2.0, text below)",
      what: "the formula engine (WebAssembly)", url: "https://github.com/ironcalc/IronCalc", file: "LICENSE-ironcalc" }],
  "core/src/text/wasm": [
    { name: "harfbuzzjs", version: "0.4.12", check: ["hb-wasm.ts", "harfbuzzjs@0.4.12"], licence: "MIT, with Apache-2.0 parts (text below)",
      what: "text shaping (WebAssembly)", url: "https://github.com/harfbuzz/harfbuzzjs", file: "LICENSE-harfbuzzjs" },
    { name: "HarfBuzz", version: "11.5.0", check: ["hb-wasm.ts", "harfbuzzjs@0.4.12"], licence: "Old MIT",
      what: "inside harfbuzzjs's WebAssembly", url: "https://github.com/harfbuzz/harfbuzz", file: "COPYING-harfbuzz" }],
};

const RULE = "=".repeat(78);
const HEAD = `Slide Builder – third-party notices

Slide Builder includes the third-party software below: each entry names it, its version and licence, where it runs
and the file its licence text comes from, then reproduces that text. Generated by tools/notices.mjs – do not edit.

Not listed because Slide Builder does not ship them:
- Python: the helper and tools/update.py use only the standard library of the Python installed on the PC (Python
  Software Foundation License, distributed with Python).
- Fonts: none ship with Slide Builder. Google Fonts families added in the font manager are downloaded when added,
  each under its own licence (SIL Open Font License 1.1, Apache-2.0 or the Ubuntu Font Licence – the folder it comes
  from in https://github.com/google/fonts: ofl/, apache/ or ufl/); Windows fonts are the PC's own.
`;

/** packages (name → {dir, version, where}) and inlined WASM folders (repo-relative) in the page's and the worker's bundles */
export async function bundled(root = ROOT) {
  const { build } = await import("esbuild");
  // the page's build-time modules (the worker string, CSS ?raw) carry no package code of their own
  const stub = { name: "stub", setup(/** @type {any} */ b) {
    b.onResolve({ filter: /^virtual:core-worker$|\?raw$/ }, (/** @type {any} */ a) => ({ path: a.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "export default ''", loader: "js" }));
  } };
  const common = { bundle: true, write: false, metafile: true, logLevel: "silent", absWorkingDir: root, format: "iife", target: "es2022", minify: true };
  const builds = {
    "the page": await build({ ...common, entryPoints: [path.join(root, "app/src/main.tsx")], plugins: [stub], jsx: "automatic", jsxImportSource: "react",
      define: { "import.meta.env.DEV": "false", "process.env.NODE_ENV": '"production"' } }),
    "the core worker": await build({ ...common, entryPoints: [path.join(root, "core/src/workers/main.ts")] }),
  };
  /** @type {Map<string, {dir: string, version: string, licence: string, url: string, where: string[]}>} */
  const packages = new Map();
  /** @type {Map<string, string[]>} */
  const wasmWhere = new Map();
  for (const [where, r] of Object.entries(builds)) {
    for (const out of Object.values(r.metafile.outputs)) for (const [file, info] of Object.entries(out.inputs)) {
      if (!info.bytesInOutput) continue;
      const f = file.replace(/\\/g, "/"), m = /^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\//.exec(f);   // (the innermost node_modules)
      if (m && !m[2].startsWith("@slide-builder/")) {
        const dir = path.resolve(root, m[1]), pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
        const p = packages.get(m[2]) || { dir, version: pj.version, licence: pj.license || "?", url: repoUrl(pj), where: [] };
        if (!p.where.includes(where)) p.where.push(where);
        packages.set(m[2], p);
      }
      const w = /(?:^|\/)(core\/src\/(?:[^/]+\/)*wasm)\/[^/]+$/.exec(f);
      if (w && !(wasmWhere.get(w[1]) || []).includes(where)) wasmWhere.set(w[1], [...(wasmWhere.get(w[1]) || []), where]);
    }
  }
  return { packages, wasmDirs: new Set(wasmWhere.keys()), wasmWhere };
}

function repoUrl(/** @type {any} */ pj) {
  const r = typeof pj.repository === "string" ? pj.repository : pj.repository?.url || pj.homepage || "";
  return r.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://");
}

const read = (/** @type {string} */ root, /** @type {string} */ rel) => fs.readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n").trimEnd();
const entry = (/** @type {string} */ head, /** @type {string} */ url, /** @type {string} */ from, /** @type {string} */ body) =>
  `\n${RULE}\n## ${head}\n${url ? url + "\n" : ""}(${from})\n\n${body}\n`;

/** the text of THIRD-PARTY-NOTICES.txt */
export async function notices(root = ROOT) {
  const { packages, wasmDirs, wasmWhere } = await bundled(root);
  let out = HEAD;
  for (const name of [...packages.keys()].sort()) {
    const p = packages.get(name), lic = fs.readdirSync(p.dir).filter(isLicence).sort();
    if (!lic.length) throw new Error(`${name} ${p.version} (bundled into ${p.where.join(" and ")}) has no licence file in ${p.dir}: add its text by hand`);
    const rel = path.relative(root, path.join(p.dir, lic[0])).replace(/\\/g, "/").replace(/^(\.\.\/)+/, "");
    out += entry(`${name} ${p.version} · ${p.licence} · ${p.where.join(" and ")}`, p.url, rel, read(p.dir, lic[0]));
  }
  for (const dir of [...wasmDirs].sort()) {
    const known = /** @type {Record<string, typeof VENDORED["core/src/calc/wasm"]>} */ (VENDORED)[dir];
    if (!known) throw new Error(`${dir}: an inlined WASM folder with no entry in tools/notices.mjs VENDORED`);
    const files = fs.readdirSync(path.join(root, dir)).filter(isLicence).sort();
    const unlisted = files.filter(f => !known.some(k => k.file === f));
    if (unlisted.length) throw new Error(`${dir}: ${unlisted.join(", ")} not listed in tools/notices.mjs VENDORED`);
    for (const k of known) {
      if (!fs.readFileSync(path.join(root, dir, k.check[0]), "utf8").slice(0, 400).includes(k.check[1]))
        throw new Error(`${dir}/${k.check[0]} is not ${k.check[1]}: update VENDORED in tools/notices.mjs`);
      out += entry(`${k.name} ${k.version} · ${k.licence} · ${wasmWhere.get(dir).join(" and ")}, ${k.what}`, k.url, `${dir}/${k.file}`, read(root, `${dir}/${k.file}`));
    }
  }
  out += entry("Apache-2.0 text · the Apache License 2.0: IronCalc's alternative licence and harfbuzzjs's Apache parts", "", APACHE, read(root, APACHE));
  return out;
}

/** app/src/ui/notices-data.ts for a text */
export function pageModule(/** @type {string} */ text) {
  const raw = Buffer.from(text, "utf8"), z = deflateSync(raw, { level: 9 });
  return `/* ${NOTICES_FILE} (${raw.length} bytes) zlib-compressed (${z.length} bytes) and base64, for ⚙ Options › About › Licences
   (ui/notices.ts inflates it when that opens). Generated by tools/notices.mjs – do not edit. */
export const NOTICES = "${z.toString("base64")}";
`;
}

async function main() {
  const text = await notices(), check = process.argv.includes("--check");
  const page = path.join(ROOT, PAGE_FILE), txt = path.join(ROOT, NOTICES_FILE);
  if (check) {
    const cur = fs.existsSync(txt) && fs.readFileSync(txt, "utf8");
    const m = fs.existsSync(page) && /NOTICES = "([^"]*)"/.exec(fs.readFileSync(page, "utf8"));
    const inPage = m && inflateSync(Buffer.from(m[1], "base64")).toString("utf8");
    const bad = [cur !== text && NOTICES_FILE, inPage !== text && PAGE_FILE].filter(Boolean);
    console.log(bad.length ? `out of date: ${bad.join(", ")} (node tools/notices.mjs)` : "third-party notices up to date");
    process.exitCode = bad.length ? 1 : 0;
    return;
  }
  fs.writeFileSync(txt, text);
  fs.writeFileSync(page, pageModule(text));
  console.log(`${NOTICES_FILE}: ${Buffer.byteLength(text)} bytes; ${PAGE_FILE}: ${fs.statSync(page).size} bytes`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
