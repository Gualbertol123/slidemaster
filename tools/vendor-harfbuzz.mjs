/* Inline the pinned HarfBuzz WASM into the core (PLAN S3.2): harfbuzzjs@0.4.12 (MIT, a devDependency of core/, its
   integrity in package-lock.json) → core/src/text/wasm/hb-wasm.ts and hb-subset-wasm.ts (base64), so the core works
   from file:// and in workers without fetching anything. core/tests/shape.test.ts fails when they differ from
   node_modules.   node tools/vendor-harfbuzz.mjs */
import { createHash } from "node:crypto";
import fs from "node:fs";
import { deflateSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PKG = path.join(ROOT, "node_modules/harfbuzzjs"), OUT = path.join(ROOT, "core/src/text/wasm");
const version = JSON.parse(fs.readFileSync(path.join(PKG, "package.json"), "utf8")).version;
if (version !== "0.4.12") throw new Error(`harfbuzzjs ${version} in node_modules, 0.4.12 pinned`);
fs.mkdirSync(OUT, { recursive: true });
for (const [file, name, out] of [["hb.wasm", "HB_WASM", "hb-wasm.ts"], ["hb-subset.wasm", "HB_SUBSET_WASM", "hb-subset-wasm.ts"]]) {
  const bytes = fs.readFileSync(path.join(PKG, file)), sha = createHash("sha256").update(bytes).digest("hex");
  const z = deflateSync(bytes, { level: 9 });                // zlib stream: fflate's unzlibSync inflates it (hb.ts)
  fs.writeFileSync(path.join(OUT, out), `/* harfbuzzjs@${version} ${file} (MIT, see ./LICENSE-harfbuzzjs), ${bytes.length} bytes, sha256 ${sha};
   zlib-compressed (${z.length} bytes) and base64. Generated by tools/vendor-harfbuzz.mjs – do not edit. */
export const ${name}_SHA256 = "${sha}";
export const ${name} = "${z.toString("base64")}";
`);
  console.log(`${out}: ${file} ${bytes.length} bytes (${z.length} compressed), sha256 ${sha}`);
}
fs.copyFileSync(path.join(PKG, "LICENSE"), path.join(OUT, "LICENSE-harfbuzzjs"));
