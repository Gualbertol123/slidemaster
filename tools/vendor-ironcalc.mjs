/* Inline the pinned IronCalc WASM engine into the core (PLAN S7.2, ADR-013): @ironcalc/wasm@0.9.0 (MIT or Apache-2.0,
   a devDependency of core/, its integrity in package-lock.json) → core/src/calc/wasm/ironcalc-wasm.ts (zlib + base64,
   as tools/vendor-harfbuzz.mjs does for HarfBuzz), ironcalc-glue.js (the wasm-bindgen glue, with its default
   "fetch wasm_bg.wasm next to the script" path removed: the core always passes the bytes) + ironcalc-glue.d.ts and
   ironcalc-snippet.js (the glue's time-zone helpers), and the licence texts. core/tests/engine.test.ts fails when the
   WASM differs from node_modules.   node tools/vendor-ironcalc.mjs */
import { createHash } from "node:crypto";
import fs from "node:fs";
import { deflateSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PKG = path.join(ROOT, "node_modules/@ironcalc/wasm"), OUT = path.join(ROOT, "core/src/calc/wasm");
const version = JSON.parse(fs.readFileSync(path.join(PKG, "package.json"), "utf8")).version;
if (version !== "0.9.0") throw new Error(`@ironcalc/wasm ${version} in node_modules, 0.9.0 pinned`);
fs.mkdirSync(OUT, { recursive: true });

const bytes = fs.readFileSync(path.join(PKG, "wasm_bg.wasm")), sha = createHash("sha256").update(bytes).digest("hex");
const z = deflateSync(bytes, { level: 9 });
fs.writeFileSync(path.join(OUT, "ironcalc-wasm.ts"), `/* @ironcalc/wasm@${version} wasm_bg.wasm (MIT or Apache-2.0, see ./LICENSE-ironcalc), ${bytes.length} bytes, sha256 ${sha};
   zlib-compressed (${z.length} bytes) and base64. Generated by tools/vendor-ironcalc.mjs – do not edit. */
export const IRONCALC_WASM_SHA256 = "${sha}";
export const IRONCALC_WASM = "${z.toString("base64")}";
`);

// the glue: snippet imports point at the sibling copy; the default URL/fetch path goes (the core passes the bytes)
const snippetDir = fs.readdirSync(path.join(PKG, "snippets"))[0];
let glue = fs.readFileSync(path.join(PKG, "wasm.js"), "utf8");
glue = glue.replace(/from '\.\/snippets\/[^']+\/inline0\.js'/g, "from './ironcalc-snippet.js'").replace(/from "\.\/snippets\/[^"]+\/inline0\.js"/g, 'from "./ironcalc-snippet.js"');
const before = glue.length;
glue = glue.replace(/\n    if \(module_or_path === undefined\) \{\n        module_or_path = new URL\('wasm_bg\.wasm', import\.meta\.url\);\n    \}\n/, "\n    if (module_or_path === undefined) throw new Error('IronCalc: the WASM bytes must be passed (core/src/calc/engine.ts)');\n");
if (glue.length === before) throw new Error("the glue's default URL path was not found: check wasm.js");
fs.writeFileSync(path.join(OUT, "ironcalc-glue.js"), `/* @ironcalc/wasm@${version} wasm.js (MIT or Apache-2.0, see ./LICENSE-ironcalc); generated by tools/vendor-ironcalc.mjs – do not edit.
   Changed from the package: the snippet import paths, and the default fetch of wasm_bg.wasm next to the script (removed). */
// @ts-nocheck
${glue}`);
fs.writeFileSync(path.join(OUT, "ironcalc-snippet.js"), `/* @ironcalc/wasm@${version} snippets/${snippetDir}/inline0.js; generated by tools/vendor-ironcalc.mjs – do not edit. */
// @ts-nocheck
${fs.readFileSync(path.join(PKG, "snippets", snippetDir, "inline0.js"), "utf8")}`);
fs.writeFileSync(path.join(OUT, "ironcalc-glue.d.ts"), `/* @ironcalc/wasm@${version} wasm.d.ts; generated by tools/vendor-ironcalc.mjs – do not edit. */\n${fs.readFileSync(path.join(PKG, "wasm.d.ts"), "utf8")}`);
