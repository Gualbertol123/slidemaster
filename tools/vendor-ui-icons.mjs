/* The app's own toolbar icons from Tabler (B35, 09 §3.5; S15.6): a small subset of @tabler/icons 3.49.0 (MIT) compiled
   into the page as app/src/ui/ui-icons.ts, independent of the packed set the core worker inflates (core/src/icons/): the
   page draws these at once, without asking the worker, and the page's bundle never carries the whole set.
   Input: the same npm release tarball as tools/vendor-tabler.mjs, verified against the same registry integrity.
       node tools/vendor-ui-icons.mjs                       fetch the tarball (network) into a temporary folder
       node tools/vendor-ui-icons.mjs <icons-3.49.0.tgz>    use a tarball fetched before (checked the same way)
   Each icon's path data is kept exactly as Tabler writes it (tabler-nodes-outline.json: every node a <path> with only a
   `d`, checked), drawn by app/src/ui/Ic.tsx on Tabler's 24 × 24 box, stroked with currentColor (width 2, round caps and
   joins), as Tabler's own SVGs. app/tests/ui-icons.test.tsx checks the names against the vendored set's index.
   To add an icon: add its Tabler name to NAMES and run the script again. */
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TARBALL, VERSION, untar } from "./vendor-tabler.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
/** the Tabler outline icons the app's toolbars use (sorted) */
export const NAMES = ["align-box-center-bottom", "align-box-center-middle", "align-box-center-top", "align-center",
  "align-left", "align-right", "arrow-back-up", "arrow-down", "arrow-forward-up", "arrow-left", "arrow-narrow-left",
  "arrow-right", "arrow-up", "arrow-up-right", "arrows-exchange", "border-all", "border-inner", "bucket-droplet",
  "chart-pie", "chevron-down", "dimensions", "eye-off", "folder-open", "layout-align-bottom", "layout-align-center",
  "layout-align-left", "layout-align-middle", "layout-align-right", "layout-align-top", "line", "line-height", "link",
  "message-circle", "message-plus", "minus", "notes", "paint", "pencil", "photo", "plus", "quote", "refresh",
  "restore", "settings", "shape", "square", "table-minus", "table-plus", "trash", "wand", "x"];

const integrity = (/** @type {Buffer} */ b) => "sha512-" + createHash("sha512").update(b).digest("base64");

export function build(/** @type {Map<string, Buffer>} */ files) {
  const nodes = JSON.parse(String(files.get("package/tabler-nodes-outline.json")));
  const lines = NAMES.map(n => {
    const ns = nodes[n];
    if (!ns) throw new Error(`no outline icon "${n}" in @tabler/icons ${VERSION}`);
    const ds = ns.map((/** @type {[string, Record<string, string>]} */ [tag, at]) => {
      if (tag !== "path" || Object.keys(at).some(k => k !== "d" && k !== "key")) throw new Error(`${n}: a <${tag}> with ${JSON.stringify(at)} (only plain paths are drawn)`);
      return at.d;
    });
    return `  ${JSON.stringify(n)}: ${JSON.stringify(ds)},`;
  });
  return `/* @tabler/icons@${VERSION} (MIT, see core/src/icons/LICENSE-tabler): ${NAMES.length} outline icons for the app's toolbars (B35),
   each icon's paths as Tabler writes them (24 × 24, stroked). Generated by tools/vendor-ui-icons.mjs – do not edit. */
export const UI_ICONS = {
${lines.join("\n")}
} as const satisfies Record<string, readonly string[]>;
export type UiIconName = keyof typeof UI_ICONS;
`;
}

async function main() {
  let [tgzFile] = process.argv.slice(2);
  if (!tgzFile) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "tabler-"));
    const r = await fetch(TARBALL.url);
    if (!r.ok) throw new Error(`${TARBALL.url}: HTTP ${r.status}`);
    tgzFile = path.join(dir, `icons-${VERSION}.tgz`);
    fs.writeFileSync(tgzFile, Buffer.from(await r.arrayBuffer()));
  }
  const tgz = fs.readFileSync(tgzFile);
  if (integrity(tgz) !== TARBALL.integrity) throw new Error(`${tgzFile}: integrity ${integrity(tgz)}, the registry's is ${TARBALL.integrity}`);
  const text = build(untar(tgz)), out = path.join(ROOT, "app/src/ui/ui-icons.ts");
  fs.writeFileSync(out, text);
  console.log(`${out}: ${NAMES.length} icons, ${text.length} bytes`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
